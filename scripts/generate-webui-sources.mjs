import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = fileURLToPath(new URL('../src/webui/app/', import.meta.url))
const outFile = fileURLToPath(new URL('../src/webui/app/sources.ts', import.meta.url))

let out = `// This file is generated by scripts/generate-webui-sources.mjs — do not edit by hand.
// It embeds the browser-side ES modules so the Node server can serve them
// without shipping raw .js assets on disk.

export const sources: Record<string, string> = {
`

const names = fs.readdirSync(dir).filter((name) => name.endsWith('.js')).sort()
for (const name of names) {
    const key = name.slice(0, -3)
    const src = fs.readFileSync(path.join(dir, name), 'utf8')
    out += `    ${JSON.stringify(key)}: ${JSON.stringify(src)},\n`
}

out = out.replace(/,\n$/, '\n') + `}\n`
fs.writeFileSync(outFile, out)
console.log('generated src/webui/app/sources.ts (' + names.length + ' modules)')
